#!/usr/bin/env python3
"""Turns the hqx shader's lookup tables (hq2x.png, hq3x.png here - libretro glsl-shaders' hqx/resources, LGPL
2.1+) into ../ab_hqx_lut.h: RGBA bytes ab_shaders.c gives the GPU's HQ2x/HQ3x pass as its aux texture.

Run it after changing a table:  python3 frontend/ab/hqx/lut_embed.py
No image library: the PNGs are 8-bit RGBA, non-interlaced, and decoded here (zlib + the five row filters).
"""
import os
import struct
import sys
import zlib

here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(here, '..', 'ab_hqx_lut.h')


def read_png(path):
    with open(path, 'rb') as f:
        data = f.read()
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        sys.exit('%s: not a PNG' % path)
    pos, idat, w = 8, b'', 0
    while pos < len(data):
        n, kind = struct.unpack('>I4s', data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if kind == b'IHDR':
            w, h, depth, ctype, _, _, interlace = struct.unpack('>IIBBBBB', body)
            if depth != 8 or ctype != 6 or interlace != 0:
                sys.exit('%s: not 8-bit RGBA non-interlaced' % path)
        elif kind == b'IDAT':
            idat += body
        pos += 12 + n
    raw = zlib.decompress(idat)
    bpp, stride = 4, w * 4
    out = bytearray()
    prev = bytearray(stride)
    for y in range(h):
        ft = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if ft == 1:
                line[i] = (line[i] + a) & 255
            elif ft == 2:
                line[i] = (line[i] + b) & 255
            elif ft == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif ft == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
            elif ft != 0:
                sys.exit('%s: row filter %d' % (path, ft))
        out += line
        prev = line
    return w, h, bytes(out)


lines = ['/* generated by frontend/ab/hqx/lut_embed.py from hq2x.png and hq3x.png there (the hqx shader\'s lookup',
         ' * tables: Copyright (C) 2014 Jules Blok, LGPL 2.1 or later - see hq2x.c) - do not edit */', '']
for scale in (2, 3):
    w, h, px = read_png(os.path.join(here, 'hq%dx.png' % scale))
    lines.append('#define AB_HQX%d_LUT_W %d' % (scale, w))
    lines.append('#define AB_HQX%d_LUT_H %d' % (scale, h))
    lines.append('static const unsigned char ab_hqx%d_lut[%d] = {' % (scale, len(px)))
    for i in range(0, len(px), 32):
        lines.append('  ' + ','.join(str(v) for v in px[i:i + 32]) + ',')
    lines.append('};')
    lines.append('')

with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(lines))
print('wrote', os.path.normpath(out_path), os.path.getsize(out_path), 'bytes')
